package com.vardhan.wallet.topup;

import com.vardhan.common.security.AuthenticatedUser;
import com.vardhan.wallet.idempotency.IdempotencyKeys;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.UUID;

@RestController
@RequestMapping("/api/topups")
@Tag(name = "Top-ups")
public class TopUpController {

    private final TopUpService topUpService;

    public TopUpController(TopUpService topUpService) {
        this.topUpService = topUpService;
    }

    @PostMapping
    @Operation(summary = "Start adding money: creates a payment order at the gateway",
            description = "Returns what the browser needs to open the payment page. The wallet is credited only "
                    + "after the gateway confirms the payment. Retrying with the same Idempotency-Key returns the same top-up.")
    public ResponseEntity<TopUpView> create(
            @AuthenticationPrincipal AuthenticatedUser user,
            @Parameter(description = "Unique per top-up attempt, e.g. a UUID generated by the client")
            @RequestHeader(IdempotencyKeys.HEADER) String idempotencyKey,
            @Valid @RequestBody CreateTopUpRequest request) {
        TopUpResult result = topUpService.create(user.userId(), idempotencyKey, request.amount());
        return ResponseEntity.status(HttpStatus.CREATED)
                .header(IdempotencyKeys.REPLAYED_HEADER, String.valueOf(result.replayed()))
                .body(result.topUp());
    }

    @GetMapping("/{topUpId}")
    @Operation(summary = "Status of one of my top-ups (poll this after paying)")
    public TopUpView get(@AuthenticationPrincipal AuthenticatedUser user, @PathVariable UUID topUpId) {
        return topUpService.get(user.userId(), topUpId);
    }

    @PostMapping("/{topUpId}/confirm")
    @Operation(summary = "Confirm a payment with the gateway's signature from the checkout",
            description = "Verifies HMAC-SHA256(order_id|payment_id) and credits the wallet if the webhook has not already done so.")
    public TopUpView confirm(@AuthenticationPrincipal AuthenticatedUser user, @PathVariable UUID topUpId,
                             @Valid @RequestBody ConfirmTopUpRequest request) {
        return topUpService.confirm(user.userId(), topUpId, request);
    }

    @PostMapping("/{topUpId}/sync")
    @Operation(summary = "Ask the gateway right now whether this top-up was paid",
            description = "The same check the reconciliation job runs on a timer; useful when a webhook was lost.")
    public TopUpView sync(@AuthenticationPrincipal AuthenticatedUser user, @PathVariable UUID topUpId) {
        return topUpService.sync(user.userId(), topUpId);
    }
}
